"""Generates the export forwarding layer of the proxy winmm.dll.

Reads the export table of the 32-bit system winmm.dll and writes:
  patch/src/gen/winmm.def          export list (same names and ordinals as the system dll)
  patch/src/gen/winmm_stubs.S      one `jmp *table[i]` stub per export
  patch/src/gen/winmm_table.h      names/ordinals for resolving the table, plus RRW_<name> indices

Every export jumps through rr_winmm_ptrs[], which proxy.c fills from the real dll and then
overrides for the functions the patch implements itself.

Usage: python tools/gen_winmm_proxy.py [path-to-32bit-winmm.dll]
Needs: pip install pefile
"""
import os
import sys

import pefile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "patch", "src", "gen")


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\SysWOW64\winmm.dll"
    pe = pefile.PE(src)
    exports = []
    for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        name = e.name.decode() if e.name else None
        exports.append((e.ordinal, name))
    exports.sort()
    os.makedirs(OUT, exist_ok=True)

    with open(os.path.join(OUT, "winmm.def"), "w", newline="\n") as f:
        f.write("LIBRARY winmm\nEXPORTS\n")
        for i, (ordinal, name) in enumerate(exports):
            if name:
                f.write(f"    {name}=rrs_{i} @{ordinal}\n")
            else:
                f.write(f"    rrs_{i} @{ordinal} NONAME\n")

    with open(os.path.join(OUT, "winmm_stubs.S"), "w", newline="\n") as f:
        f.write("/* generated by tools/gen_winmm_proxy.py */\n")
        f.write("    .data\n    .globl _rr_winmm_ptrs\n    .p2align 2\n")
        f.write(f"_rr_winmm_ptrs:\n    .space {4 * len(exports)}\n")
        f.write("    .text\n")
        for i, _ in enumerate(exports):
            f.write(f"    .globl _rrs_{i}\n_rrs_{i}:\n    jmp *(_rr_winmm_ptrs+{4 * i})\n")

    with open(os.path.join(OUT, "winmm_table.h"), "w", newline="\n") as f:
        f.write("/* generated by tools/gen_winmm_proxy.py */\n#pragma once\n")
        f.write(f"#define RR_WINMM_COUNT {len(exports)}\n")
        f.write("static const struct { const char *name; unsigned short ordinal; } rr_winmm_exports[] = {\n")
        for ordinal, name in exports:
            f.write(f'    {{ {chr(34) + name + chr(34) if name else "0"}, {ordinal} }},\n')
        f.write("};\n")
        for i, (ordinal, name) in enumerate(exports):
            if name:
                f.write(f"#define RRW_{name} {i}\n")
    print(f"{len(exports)} exports from {src} -> {OUT}")


if __name__ == "__main__":
    main()
